package com.example.cargotracker.simulation.domain.model.valueobjects;

/**
 * 業務シミュレーションの工程（US33 §受入基準 1 / US34 §受入基準 1）。
 *
 * <p><b>業務の言葉で並べる。</b> 画面は「どの工程で止まったか」を読む人のために
 * あるので、`POST /api/v1/booking/bookings` ではなく「予約の登録」と出す。</p>
 *
 * <p><b>呼ぶ API は工程が知らない。</b> ここにあるのは業務の段取りだけで、
 * どの経路を叩くかは実行側が決める——段取りと経路を同じ場所に書くと、
 * API を変えるたびにシナリオの定義が動く。</p>
 */
public enum StepKind {

    /** 荷主を登録する。**シミュレーション由来の印はここで付く**（注 N3）。 */
    REGISTER_SHIPPER("荷主の登録"),
    /** 貨物予約を登録する。 */
    REGISTER_BOOKING("予約の登録"),
    /** 経路設計へ引き渡す。 */
    REQUEST_ROUTING("経路設計への引き渡し"),
    /** 経路候補から 1 つ選んで確定する。**候補 0 件はここで止まる**。 */
    ASSIGN_ROUTE("経路の確定"),
    /** 荷主へ通知した記録を残す（送信基盤はスコープ外）。 */
    NOTIFY_SHIPPER("荷主への通知"),
    /** 予約を確定する。 */
    CONFIRM_BOOKING("予約の確定"),
    /** 追跡番号を発行する。**ここから追跡と荷役が始まる**。 */
    ISSUE_TRACKING_NUMBER("追跡番号の発行"),
    /** 受領・積込・荷降しを順に記録する。 */
    RECORD_HANDLING("荷役の記録"),
    /** 通関申告を出して通関済にする。**引取の前提**（US29）。 */
    CLEAR_CUSTOMS("通関"),
    /** 荷受人の確認を取って引取を記録する。 */
    CLAIM_CARGO("引取"),
    /** 輸送料金が算出されるのを待つ（連鎖が作る）。 */
    CALCULATE_INVOICE("料金の算出"),
    /** 請求書を発行する。 */
    ISSUE_INVOICE("請求書の発行"),
    /** 入金を記録する。**ここで予約が精算済になる**。 */
    RECORD_PAYMENT("入金の記録"),
    /**
     * 例外を起票する（US35）。
     *
     * <p><b>種類ごとに工程を作らない</b>（IT17 の注 N10）。遅延・破損・誤配・
     * 税関保留で起こすことは同じで、違うのは<b>入力（例外種別）だけ</b>である。
     * 5 種類それぞれに工程を足すと列挙が肥大し、扱っていない場所が名乗り出ない
     * まま増える（「列挙に値を足したら全箇所を回る」）。</p>
     */
    REGISTER_EXCEPTION("例外の起票"),
    /**
     * 経路外の港で荷役を記録し、**システムに誤配を起票させる**（US35 §受入基準 3）。
     *
     * <p><b>誤配は手で起票できない</b>（実物が断った）。荷役が決めることなので、
     * 手で起票できると「起きていない誤配」を記録でき、経路設計者はそれを
     * 組み直そうとする。<b>本番と同じ出来事から起こす</b>。</p>
     */
    RECORD_OFF_ROUTE_HANDLING("経路外での荷役"),
    /**
     * 通関を留置し、**システムに税関保留を起票させる**（US35 §受入基準 1）。
     *
     * <p><b>税関保留も手で起票できない</b>（通関が決める）。誤配と同じ理由。</p>
     */
    HOLD_CUSTOMS("通関の留置"),
    /** 例外の対応を始める（US35）。 */
    RESPOND_TO_EXCEPTION("例外の対応"),
    /** 例外を解決する（US35）。 */
    RESOLVE_EXCEPTION("例外の解決"),
    /**
     * 現在地からの経路を組み直す（US35 §受入基準 3）。
     *
     * <p><b>経路の確定（{@link #ASSIGN_ROUTE}）と分ける。</b> 同じ API を叩くが、
     * <b>待つ相手が違う</b>——初回は「旅程が入ったか」で、組み直しは
     * 「<b>前と違う旅程になったか</b>」である。同じ工程で 2 度並べると、
     * 2 度目の待ちが最初から満たされていて何も確かめない（空振り）。</p>
     */
    REASSIGN_ROUTE("経路の組み直し"),
    /**
     * 受領と積込を記録して、**貨物を輸送中にする**（US35 §受入基準 4）。
     *
     * <p><b>輸送前のキャンセルは承認を要らない</b>（実物で確かめた）——
     * 即座にキャンセルされる。承認と陸揚げ地の指定を確かめたいので、
     * <b>先に輸送中にする</b>。荷降しまで記録すると輸送が終わってしまうので、
     * {@link #RECORD_HANDLING} とは分ける。</p>
     */
    LOAD_CARGO("受領と積込"),
    /** 輸送中のキャンセルを申請する（US35 §受入基準 4）。 */
    REQUEST_CANCELLATION("キャンセルの申請"),
    /** キャンセルを承認し、**陸揚げ地を指定する**（US35 §受入基準 4）。 */
    APPROVE_CANCELLATION("キャンセルの承認"),
    /** 指定された港で荷降しする。**ここで追跡が閉じる**（US35 §受入基準 4）。 */
    DISCHARGE_CANCELLED("指定港での荷降し");

    private final String label;

    StepKind(String label) {
        this.label = label;
    }

    /** 画面に出す呼び名。<b>列挙名を出さない</b>（読む人は業務の言葉で読む）。 */
    public String label() {
        return label;
    }
}
