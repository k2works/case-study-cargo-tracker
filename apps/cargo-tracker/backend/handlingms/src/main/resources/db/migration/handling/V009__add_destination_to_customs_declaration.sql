-- 輸入港を通関申告に持つ（IT13 / IT12 レビュー #L17）。
--
-- **留置の営業日は輸入港の国の暦で数える。** 日本固定にしていたころ、
-- HolidayCalendar の国別分岐は本番の経路で一度も踏まれていなかった
-- （検査だけが国を切り替えていた）。数えるのは読むときなので、読み取り
-- モデルにも輸入港が要る。
--
-- **NULL を許す。** 列が無かったころに登録された申告には入っていない
-- （不変条件を足すと既存の行が読めなくなる）。NULL のときは日本の暦で
-- 数える——足りないことは「早く点く」側に倒れる。
ALTER TABLE customs_declaration ADD COLUMN destination_unlocode VARCHAR(5);
