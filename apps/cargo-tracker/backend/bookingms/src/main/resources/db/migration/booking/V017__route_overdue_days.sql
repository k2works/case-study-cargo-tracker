-- 誤配の再設計で到着期限を何日超えたか（IT11 / US28 §受入基準 6）。
--
-- 正典: docs/design/cargo-tracker/data-model.md「cargo_summary」
--
-- **超過は「差分が明示される」ための値である。** 誤配でいちばん困るのは、
-- 間に合わないことに誰も気づけないまま船が動くことなので、予約詳細（S22）は
-- 再設計後に「当初の期限より N 日遅れます」を出し、荷主への通知内容にも含める。
--
-- **通常の設計では必ず 0**（不変条件 5）。列が 0 でないのは、その予約が
-- 誤配を経て組み直された証拠になる。
--
-- **NULL を許す。** 既存の行は「まだ再設計していない」であって「0 日超過」では
-- ない。既定値で埋めると、この 2 つを区別できなくなる。

ALTER TABLE cargo_summary
    ADD COLUMN route_overdue_days INTEGER;
