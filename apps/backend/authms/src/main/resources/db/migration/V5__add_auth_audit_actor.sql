-- 監査ログに「誰が操作したか」を残す（US32-3）。
--
-- これまでの列は「誰に起きたか」（username）と「いつ」（occurred_at）だけだった。
-- ログインは本人の操作なので両者が一致するが、**管理者による解除は違う**。
-- 誰が解除したかが残らないと、US32-3（誰が・いつ・どのアカウントを）を満たせない。
--
-- NOT NULL にしない。列が無かったころの行（IT1〜IT5 の認証ログ）が読めなくなる。
-- ログインのように本人の操作である事象では NULL のままでよい（username と同じだからである）。
ALTER TABLE auth_audit_log ADD COLUMN actor VARCHAR(50);
