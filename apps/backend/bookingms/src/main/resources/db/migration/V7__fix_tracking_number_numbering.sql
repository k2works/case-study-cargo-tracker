-- 追跡番号の採番を直す（IT6 のクローズレビュー）。
--
-- 問題 1: **番号が重複しうる。**
--   `LPAD(CAST(NEXTVAL(...) AS VARCHAR), 4, '0')` は 4 桁を超えると<strong>切り詰める</strong>
--   （PostgreSQL の LPAD は長さを超えた分を落とす）。10000 は '1000' になる。形式違反では
--   落ちないため、UNIQUE 制約に当たるまで誰も気づかない。
--   → 採番の上限を 9999 にし、循環させる。**重複は UNIQUE 制約が必ず捕まえる**形にする。
--   1 日あたり 9,999 件を超える発行が必要になったら、日付ごとのカウンタへ作り替える
--   （IT7 の返済枠。ここで作り込まないのは、いまの業務量から遠いためである）。
--
-- 問題 2: **日付が DB のタイムゾーンで決まっていた。**
--   `CURRENT_DATE` はセッションのタイムゾーン（コンテナは通常 UTC）で決まる。アプリは
--   業務タイムゾーン（Asia/Tokyo）の Clock を使っており、**日本時間の 00:00〜09:00 に
--   発行した番号は前日の日付を持つ**。「番号だけでいつごろの貨物か分かる」という目的が
--   1 日 9 時間ぶん外れる。このプロジェクトは同じ形の食い違いを 3 度踏んでいる。
--   → 日付はアプリが業務タイムゾーンの Clock から渡す。組み立て（形式）は DB が持つ
--   （[ADR-011]）。**時刻源を 1 つにする**という規律のほうを優先する。

DROP SEQUENCE tracking_number_seq;
CREATE SEQUENCE tracking_number_seq START WITH 1 INCREMENT BY 1 MAXVALUE 9999 CYCLE;
