-- 動作確認用の荷主（実業務の帯）。
--
-- **これが無いと、荷主の利用者はシミュレーションの荷主に紐付く。**
-- authms の V7 は shipper01 を `shipper_id = 1` へ決め打ちで紐付けているが、
-- bookingms は荷主の種を持たなかった。その結果、1 番が誰になるかは
-- **その環境で最初に登録された荷主**で決まる——DB を初期化した直後の 1 番は、
-- シミュレーションが作った荷主だった（`SIM-000001`）。
-- 荷主の画面を開くと、自社の貨物として架空の案件が並ぶ。
--
-- **番号を予約する。** id を採番に任せると、環境ごとに違う番号になり、
-- authms の紐付けが同じ相手を指さなくなる。9001 番から先を動作確認用として
-- 予約し、`BIGSERIAL` の採番（1 から）とぶつからない位置に置く。
-- 9000 件の荷主が登録されるまで衝突しない。
--
-- **`shipper_code` は実業務の帯にする**（`SIM-` で始めない）。始めると
-- [ADR-030] 決定 3 によって一覧から外れ、動作確認の役に立たない。
--
-- 本番環境ではこのマイグレーションを適用しない（正規の荷主登録手順を用いる）。
-- **個人にする。** 法人は契約番号が無いと集約が復元できない
-- （`Shipper` の不変条件「法人荷主には契約番号が必要です」）。契約の妥当性を
-- 確かめたいのではなく、荷主の画面を確かめたいので個人で足りる。
