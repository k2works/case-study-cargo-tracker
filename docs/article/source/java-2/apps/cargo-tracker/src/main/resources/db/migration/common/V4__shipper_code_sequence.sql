-- 荷主コードの採番をシーケンスに移す（IT1 持ち越し C5）。
--
-- これまでは MAX(shipper_code) + 1 で採番していた。**2 人が同時に登録すると
-- 両者が同じ最大値を読み、同じ荷主コードを採番する。** 片方は UNIQUE 制約で
-- 落ちるため実害はデータ破壊ではなく「登録に失敗する」ことだが、
-- 現場では原因の分からない失敗として現れる。
--
-- シーケンスはトランザクションの外で進むため、同時採番でも重複しない。
-- 採番した番号がロールバックで飛ぶことはあるが、荷主コードは連続性を
-- 要件としていない（識別できればよい）。
--
-- **既存データとの整合（setval）はここに置かない。** setval は H2 に存在せず、
-- common/ に置くとローカル起動が落ちる（実測）。PostgreSQL 固有の処理は
-- postgresql/ に隔離する（ADR-003）。H2 はローカル起動専用で常に空のため、
-- 整合を取る対象がそもそも無い。

CREATE SEQUENCE shipper_code_seq START WITH 1 INCREMENT BY 1;
