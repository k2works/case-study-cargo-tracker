-- 荷役作業に追跡番号を残す（IT7 返済枠 / IT6 レビュー H12）。
--
-- 荷役一覧には予約 ID しか出ていなかった。**作業員が手にしているのは追跡番号だけ**であり、
-- 予約 ID は紙にもラベルにも書かれていない。自分が今登録した作業を一覧で探せない。
--
-- 追跡番号を join で引かない。handling_activity から cargo を join すると、
-- Handling Context の SQL が Booking Context のテーブルを読むことになり、
-- BC の境界が SQL の中で消える（唯一の越境点は ACL ポートである）。
--
-- 列として持つのは非正規化ではあるが、**追跡番号は作業員が実際に読み取った値**であり、
-- 「そのとき何を読み取ったか」は荷役作業そのものの事実である。予約への参照ではない。
-- 読み取りを誤って別の貨物に登録した場合も、誤った番号がそのまま残るほうが追跡できる。
--
-- 既存行は NULL である。IT6 で登録された作業には読み取った番号の記録が無く、
-- **後から埋めると「記録されていたこと」と区別がつかなくなる。**

ALTER TABLE handling_activity
    ADD COLUMN tracking_number VARCHAR(20);
