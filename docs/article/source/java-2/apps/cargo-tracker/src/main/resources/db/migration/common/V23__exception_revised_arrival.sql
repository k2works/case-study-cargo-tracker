-- 例外の対応で決まった「新しい到着予定日」（US19 の受入基準 / IT11 C18）。
--
-- 受入基準は「対応内容（**新しい到着予定日**・対応方針）を入力して」と書いている。
-- IT10 は自由記述だけを用意し、括弧の中を構造化しなかった。荷主が遅延で
-- いちばん知りたいのは「結局いつ着くのか」であり、文章に埋もれると
-- 追跡照会の到着予定と食い違って問い合わせが増える。
--
-- **NULL 可にする。** 理由は 2 つある。
--   1. IT10 までに起票・解決された例外にはこの値が無い
--   2. 破損・紛失の対応では到着予定が変わらないことがあり、必須にすると
--      変わっていない日付を入れさせることになる
--
-- **読み戻す側は NULL を拒んではならない。** 拒むと、列が無かったころの
-- 例外を持つ貨物が集約ごと読めなくなり、その貨物の画面が 500 になる
-- （IT10 で location_unlocode に同じ形の欠陥を作り、レビューで見つかった）。
-- この責務は ExceptionResolution の復元経路に対するテストで固定する。
ALTER TABLE tracking_exception_event ADD COLUMN revised_arrival DATE;
