-- 引取確認コード（US35）。
--
-- IT7 の引取記録は **提示された値をそのまま書き写すだけ**で、照合する相手が
-- システムの中に無かった。**記録はできるが証明にならない**（IT7 レビュー H4）。
--
-- **追跡番号とは別の列にする。** 追跡番号は荷主が取引先へ転送することを
-- 前提にした「合鍵」であり（公開追跡は認証を持たない相手に見せる）、
-- **それを知っているだけで引き取れてはならない**。
--
-- **NULL 可にする。** 確定前の予約は持たないし、この列が無かったころに
-- 確定した予約にも値が無い。読み戻す側は NULL を拒んではならない
-- （V22 / V23 / V24 / V25 と同じ判断）。**不変条件の追加は既存行を壊す。**
--
-- **UNIQUE にしない。** 採番は予測しにくい値だが、衝突しないことを
-- 業務の不変条件として名乗るには足りない。照合は予約 1 件の中で行うため、
-- 全社で一意である必要がない。
ALTER TABLE cargo ADD COLUMN claim_code VARCHAR(12);
