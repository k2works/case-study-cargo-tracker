-- 利用者と荷主の紐付け（US34 / IT9）。
--
-- **IT2 から 7 イテレーション積み上がった制約を解くための列である。**
-- 貨物予約一覧を荷主に開放したとき、利用者アカウントと荷主を結びつける手段が無く、
-- 他社の予約まで見える状態だった。以来「US34 で紐付けを作ってから開放する」と
-- 書き続けてきた（予約一覧・追跡の認証つき一覧・末尾 4 桁検索・自社貨物一覧）。
--
-- **NULL を許す。** 社内ロール（営業・経路設計者・追跡管理者・荷役作業員・管理者）は
-- 荷主に紐づかない。全員が紐づく形にすると、社内利用者を作るたびにダミーの荷主が要る。
--
-- **FK を張る。** 荷主が消えたときに宙に浮いた紐付けが残ると、
-- 「誰の予約も見えない利用者」ではなく「存在しない荷主の予約を探す利用者」になる。
ALTER TABLE users
    ADD COLUMN shipper_id UUID REFERENCES shipper (id);

-- 紐付けから利用者を引くことは無い（利用者から荷主を引く）。
-- ログインのたびに引くため、利用者側の検索経路（username の UK）で足りる。
--
-- **COMMENT ON は書かない。** common/ は方言に依らない SQL だけを置く場所であり、
-- 列の意図は data-model.md（正典）に書く（IT6 の方言漏れの教訓）。
